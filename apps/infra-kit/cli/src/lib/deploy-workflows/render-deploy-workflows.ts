import type { DeployConfig, DeployService } from '@slip-stream-kit/config/internal'

import packageJson from '../../../package.json' with { type: 'json' }

/**
 * The commit both shared jobs are pinned to: callers live in other orgs, where a moving ref would let
 * any push to this repo change what their deploys run. Bump it (and release) whenever
 * `.github/workflows/ik-deploy-service.yml` or `ik-install-deps.yml` changes; `deploy-sync` then moves
 * every consumer forward.
 */
const SHARED_JOBS_SHA = '9a33a1e85e5b868036100055fc24c1cdd5674f13'

export const SHARED_DEPLOY_JOB = `ArthurSaenz/infra-kit/.github/workflows/ik-deploy-service.yml@${SHARED_JOBS_SHA}`

export const SHARED_INSTALL_JOB = `ArthurSaenz/infra-kit/.github/workflows/ik-install-deps.yml@${SHARED_JOBS_SHA}`

const INSTALL_JOB = 'install-deps'

/** GitHub refuses to dispatch a workflow with more inputs than this. */
const MAX_DISPATCH_INPUTS = 25

/** The first line of every generated workflow; readers use it to tell these files from hand-written ones. */
export const GENERATED_MARKER = '# Generated by `infra-kit deploy-sync` from infra-kit.deploy.ts'

const SKIP_TERRAFORM_INPUT = 'skip_terraform_deploy'

type WorkflowKind = 'all' | 'selected'

interface KindNames {
  file: string
  title: string
  concurrency: string
}

/**
 * The pilot files, named `-v2` and numbered 91/92 beside the hand-written v1 files the CLI's
 * `release deploy-*` dispatches; and the v1 names and titles they take over under `replaceV1`. Each
 * kind keeps its v1 concurrency group either way, so a pilot run waits for a v1 run of the same kind.
 */
const KINDS: Record<'pilot' | 'v1', Record<WorkflowKind, KindNames>> = {
  pilot: {
    all: { file: 'deploy-all-v2.yml', title: '91 🧪 Deploy all (v2)', concurrency: 'deploy-all' },
    selected: { file: 'deploy-selected-v2.yml', title: '92 🧪 Deploy selected (v2)', concurrency: 'deploy-selected' },
  },
  v1: {
    all: { file: 'deploy-all.yml', title: '01 ⚙️ Deploy all', concurrency: 'deploy-all' },
    selected: {
      file: 'deploy-selected-services.yml',
      title: '02 ⚙️ Deploy selected services',
      concurrency: 'deploy-selected',
    },
  },
}

const kindNames = (config: DeployConfig, kind: WorkflowKind): KindNames => {
  return KINDS[config.replaceV1 === true ? 'v1' : 'pilot'][kind]
}

const workflowPaths = (naming: 'pilot' | 'v1'): string[] => {
  return Object.values(KINDS[naming]).map(({ file }) => {
    return `.github/workflows/${file}`
  })
}

/** The `-v2` pilot pair, which `replaceV1` leaves stale. */
export const PILOT_WORKFLOW_PATHS = workflowPaths('pilot')

/** The v1-named pair, which `replaceV1` generates and which delivery dispatches. */
export const V1_WORKFLOW_PATHS = workflowPaths('v1')

export interface GeneratedWorkflow {
  /** Repo-relative path. */
  path: string
  content: string
}

interface PlannedService {
  name: string
  service: DeployService
  /** The offered environments it may deploy to; `undefined` = all of them, so no gate is emitted. */
  gate: string[] | undefined
}

/** `_terraform-apply-initUser-jobs.yml` → `terraform-apply-initUser`. */
const jobIdForWorkflow = (file: string): string => {
  return file.replace(/^_/, '').replace(/(?:-jobs)?\.ya?ml$/, '')
}

/** Services in manifest order, each with its env gate narrowed to the environments this workflow offers. */
const planServices = (config: DeployConfig, kind: WorkflowKind): PlannedService[] => {
  return Object.entries(config.services).flatMap(([name, service]) => {
    if (kind === 'all' && service.deployAll === false) return []

    const allowed = config.environments.filter((env) => {
      return (service.envs?.includes(env) ?? true) && !(service.skipEnvs?.includes(env) ?? false)
    })

    if (allowed.length === 0) return []

    return [{ name, service, gate: allowed.length === config.environments.length ? undefined : allowed }]
  })
}

/** A GitHub Actions expression, `${{ … }}`. */
const gh = (expression: string): string => {
  return `\${{ ${expression} }}`
}

/** A secret named after the dispatched environment, e.g. `arthur_AWS_REGION`, as v1 looks them up. */
const envSecret = (suffix: string): string => {
  return gh(`secrets[format('{0}_${suffix}', inputs.environment)]`)
}

/**
 * The jobs every service waits for: the install, terraform (which may be skipped per run) and the
 * pre-deploy jobs. All but terraform must succeed.
 */
interface Upstream {
  terraform: string[]
  preDeploy: string[]
}

const upstreamJobs = (upstream: Upstream): string[] => {
  return [INSTALL_JOB, ...upstream.terraform, ...upstream.preDeploy]
}

const terraformOk = (terraformJobs: string[]): string[] => {
  return terraformJobs.map((job) => {
    return `(needs.${job}.result == 'success' || needs.${job}.result == 'skipped')`
  })
}

const upstreamOk = (upstream: Upstream): string[] => {
  return [
    `needs.${INSTALL_JOB}.result == 'success'`,
    ...terraformOk(upstream.terraform),
    ...upstream.preDeploy.map((job) => {
      return `needs.${job}.result == 'success'`
    }),
  ]
}

/**
 * The env gate is written as `contains(fromJSON(...), inputs.environment)` and never as
 * `inputs.environment == '<env>'`: the workflow-gates reader in CLIs before deploy-sync's
 * `replaceV1` scans every workflow for the latter, and consumers run whichever CLI is installed.
 */
const serviceCondition = (planned: PlannedService, kind: WorkflowKind, upstream: Upstream): string => {
  const parts: string[] = []

  if (kind === 'selected') parts.push(`inputs.${planned.name}`)

  if (planned.gate !== undefined)
    parts.push(`contains(fromJSON('${JSON.stringify(planned.gate)}'), inputs.environment)`)

  parts.push('!cancelled()', ...upstreamOk(upstream))

  return gh(parts.join(' && '))
}

const needsLine = (jobs: string[]): string[] => {
  return jobs.length === 0 ? [] : [`    needs: [ ${jobs.join(', ')} ]`]
}

const ifLine = (condition: string | undefined): string[] => {
  return condition === undefined ? [] : [`    if: ${condition}`]
}

const localWorkflowCall = (file: string): string[] => {
  return [
    `    uses: ./.github/workflows/${file}`,
    '    with:',
    `      branch: ${gh('github.ref')}`,
    `      environment: ${gh('inputs.environment')}`,
    '    secrets: inherit',
  ]
}

const sharedJobCall = (planned: PlannedService, config: DeployConfig): string[] => {
  const extraEnv = config.extraEnv ?? []
  const runner = planned.service.runner === undefined ? [] : [`      runner: ${planned.service.runner}`]
  const timeout =
    config.deployTimeoutMinutes === undefined ? [] : [`      timeout-minutes: ${config.deployTimeoutMinutes}`]
  // A service with a TypeScript deploy runs it through `infra-kit deploy-run`, with the CLI generating
  // this file: a branch deploys with the toolkit it was generated by. Without one, the job runs the .sh.
  const deployRun = planned.service.deploy === undefined ? [] : [`      infra-kit-version: ${packageJson.version}`]
  const extra =
    extraEnv.length === 0
      ? []
      : [
          '      extra-env: |',
          ...extraEnv.map((secret) => {
            const value = gh(`secrets.${secret}`)

            return `        ${secret}=${value}`
          }),
        ]

  return [
    `    uses: ${SHARED_DEPLOY_JOB}`,
    '    with:',
    `      environment: ${gh('inputs.environment')}`,
    `      ref: ${gh('github.ref')}`,
    `      sha: ${gh('github.sha')}`,
    `      service: ${planned.name}`,
    ...deployRun,
    ...runner,
    ...timeout,
    '    secrets:',
    `      aws-access-key-id: ${envSecret('AWS_ACCESS_KEY_ID')}`,
    `      aws-secret-access-key: ${envSecret('AWS_SECRET_ACCESS_KEY')}`,
    `      aws-region: ${envSecret('AWS_REGION')}`,
    `      serverless-access-key: ${gh('secrets.SERVERLESS_ACCESS_KEY')}`,
    `      slack-token: ${gh('secrets.SLACK_TOKEN')}`,
    `      slack-channel: ${gh('secrets.SLACK_CHANNEL')}`,
    ...extra,
  ]
}

const serviceJob = (
  planned: PlannedService,
  kind: WorkflowKind,
  upstream: Upstream,
  config: DeployConfig,
): string[] => {
  const call =
    planned.service.workflow === undefined
      ? sharedJobCall(planned, config)
      : localWorkflowCall(planned.service.workflow)

  return [
    '',
    `  deploy-${planned.name}:`,
    ...needsLine(upstreamJobs(upstream)),
    ...ifLine(serviceCondition(planned, kind, upstream)),
    ...call,
  ]
}

const booleanInput = (name: string, description: string): string[] => {
  return [
    '',
    `      ${name}:`,
    '        type: boolean',
    `        description: '${description}'`,
    '        required: false',
    '        default: false',
  ]
}

const dispatchInputs = (config: DeployConfig, kind: WorkflowKind, services: PlannedService[]): string[] => {
  const environment = [
    '      environment:',
    '        type: choice',
    "        description: 'Environment for deploy'",
    '        required: true',
    `        default: '${config.defaultEnvironment ?? config.environments[0]}'`,
    '        options:',
    ...config.environments.map((env) => {
      return `          - ${env}`
    }),
  ]
  const terraform =
    (config.terraform ?? []).length > 0 ? booleanInput(SKIP_TERRAFORM_INPUT, 'Skip terraform deployment') : []
  const perService =
    kind === 'all'
      ? []
      : services.flatMap((planned) => {
          const only = planned.gate === undefined ? '' : ` (${planned.gate.join(', ')} only)`

          return booleanInput(planned.name, `Deploy ${planned.name}${only}`)
        })

  return ['on:', '  workflow_dispatch:', '    inputs:', ...environment, ...terraform, ...perService]
}

/** `client-be client-fe `: the checked services, as v1's deploy-selected titles its runs. */
const selectedServicesTitle = (services: PlannedService[]): string => {
  return services
    .map((planned) => {
      return gh(`inputs.${planned.name} && ''${planned.name} '' || ''''`)
    })
    .join('')
}

const header = (config: DeployConfig, kind: WorkflowKind, services: PlannedService[]): string[] => {
  const { title, concurrency } = kindNames(config, kind)
  const skipTf =
    (config.terraform ?? []).length > 0 ? gh(`inputs.${SKIP_TERRAFORM_INPUT} && '' — skip TF'' || ''''`) : ''
  const checked = kind === 'selected' ? ` — ${selectedServicesTitle(services)}` : ''

  return [
    `${GENERATED_MARKER}: edit that file and re-run the command,`,
    '# a hand edit here is overwritten.',
    `name: '${title}'`,
    `run-name: '${title} [${gh('inputs.environment')}]${skipTf}${checked}'`,
    '',
    `# The v1 ${kind === 'all' ? 'deploy-all' : 'deploy-selected'} group: two runs of this kind, v1 or v2, never deploy into one`,
    '# environment at once.',
    'concurrency:',
    `  group: ${concurrency}-${gh('inputs.environment')}`,
    '  # false: a cancelled run would also kill an in-flight terraform apply.',
    '  cancel-in-progress: false',
    '',
  ]
}

const terraformJob = (file: string): string[] => {
  const unlessSkipped = gh(`!inputs.${SKIP_TERRAFORM_INPUT}`)

  return ['', `  ${jobIdForWorkflow(file)}:`, `    if: ${unlessSkipped}`, ...localWorkflowCall(file)]
}

/** Runs even when terraform was skipped: what it prepares (a layer, an artefact) the services still read. */
const preDeployJob = (file: string, terraformJobs: string[]): string[] => {
  const condition =
    terraformJobs.length === 0 ? undefined : gh(['!cancelled()', ...terraformOk(terraformJobs)].join(' && '))

  return [
    '',
    `  ${jobIdForWorkflow(file)}:`,
    ...needsLine(terraformJobs),
    ...ifLine(condition),
    ...localWorkflowCall(file),
  ]
}

/** Runs beside terraform, as v1's validate-cache does: neither needs the other. */
const installJob = (): string[] => {
  return [
    '',
    `  ${INSTALL_JOB}:`,
    `    uses: ${SHARED_INSTALL_JOB}`,
    '    with:',
    `      ref: ${gh('github.ref')}`,
    `      sha: ${gh('github.sha')}`,
    '    secrets:',
    `      slack-token: ${gh('secrets.SLACK_TOKEN')}`,
    `      slack-channel: ${gh('secrets.SLACK_CHANNEL')}`,
  ]
}

/** GitHub rejects a workflow with a duplicate job id only at dispatch; this fails at sync instead. */
const assertUniqueJobIds = (ids: string[], file: string): void => {
  const seen = new Set<string>()

  for (const id of ids) {
    if (seen.has(id)) throw new Error(`${file} would declare job \`${id}\` twice; rename one of the workflows`)

    seen.add(id)
  }
}

const notifyJob = (file: string, deployJobs: string[]): string[] => {
  return [
    '',
    '  notify-success:',
    ...needsLine(deployJobs),
    `    if: ${gh("!cancelled() && contains(needs.*.result, 'success') && !contains(needs.*.result, 'failure')")}`,
    `    uses: ./.github/workflows/${file}`,
    '    secrets: inherit',
  ]
}

const renderWorkflow = (config: DeployConfig, kind: WorkflowKind): GeneratedWorkflow => {
  const services = planServices(config, kind)
  const terraformFiles = config.terraform ?? []
  const preDeployFiles = config.preDeploy ?? []
  const upstream: Upstream = {
    terraform: terraformFiles.map(jobIdForWorkflow),
    preDeploy: preDeployFiles.map(jobIdForWorkflow),
  }
  const { file } = kindNames(config, kind)
  const inputCount = 1 + (terraformFiles.length > 0 ? 1 : 0) + (kind === 'selected' ? services.length : 0)

  // Only deploy-selected has an input per service, so only it can reach the cap.
  if (inputCount > MAX_DISPATCH_INPUTS) {
    const fixed = terraformFiles.length > 0 ? `environment, ${SKIP_TERRAFORM_INPUT}` : 'environment'

    throw new Error(
      `${file} would need ${inputCount} dispatch inputs (${fixed} and one checkbox per service); GitHub allows ${MAX_DISPATCH_INPUTS}. Fold services that always deploy together into one deploy script.`,
    )
  }

  const deployJobs = services.map((planned) => {
    return `deploy-${planned.name}`
  })

  assertUniqueJobIds(
    [
      INSTALL_JOB,
      ...upstream.terraform,
      ...upstream.preDeploy,
      ...deployJobs,
      ...(config.notifySuccess === undefined ? [] : ['notify-success']),
    ],
    file,
  )

  const lines = [
    ...header(config, kind, services),
    ...dispatchInputs(config, kind, services),
    '',
    'permissions:',
    '  contents: read',
    '',
    'jobs:',
    ...installJob(),
    ...terraformFiles.flatMap(terraformJob),
    ...preDeployFiles.flatMap((file) => {
      return preDeployJob(file, upstream.terraform)
    }),
    ...services.flatMap((planned) => {
      return serviceJob(planned, kind, upstream, config)
    }),
    ...(config.notifySuccess === undefined ? [] : notifyJob(config.notifySuccess, deployJobs)),
  ]

  // The first job follows `jobs:` directly; every later one is separated by a blank line.
  const content = `${lines.join('\n').replace('jobs:\n\n', 'jobs:\n')}\n`

  return { path: `.github/workflows/${file}`, content }
}

/**
 * The deploy-all and deploy-selected workflows a manifest describes. Pure: the same manifest always
 * renders byte-identical files, which is what lets `deploy-sync --check` compare them with disk.
 *
 * @example
 * renderDeployWorkflows({ environments: ['dev'], services: { 'client-be': {} } }).map((w) => w.path)
 * // => ['.github/workflows/deploy-all-v2.yml', '.github/workflows/deploy-selected-v2.yml']
 * renderDeployWorkflows({ ...manifest, replaceV1: true }).map((w) => w.path)
 * // => ['.github/workflows/deploy-all.yml', '.github/workflows/deploy-selected-services.yml']
 */
export const renderDeployWorkflows = (config: DeployConfig): GeneratedWorkflow[] => {
  return [renderWorkflow(config, 'all'), renderWorkflow(config, 'selected')]
}
